// Icons the SAP shell / launchpad / cards render directly with <Icon name="…"/>, beyond MAP
const EXTRA = [
  "employee", "customer", "sales-order", "money-bills", "line-chart", "pie-chart", "lead",
  "sales-quote", "hint", "log", "navigation-right-arrow", "product", "inventory", "cart", "group",
];

const read = (name) => {
  const file = `${DIR}/v5/${name}.js`;
  if (!fs.existsSync(file)) return null;
  const src = fs.readFileSync(file, "utf8");
  const d = src.match(/const pathData = "([^"]+)"/)?.[1];
  const vb = src.match(/const viewBox = "([^"]+)"/)?.[1];
  return d && vb ? { d, vb } : null;
};

const missing = [];
const out = {};
let viewBox = null;
for (const [lucide, sap] of Object.entries(MAP)) {
  const icon = read(sap);
  if (!icon) { missing.push(`${lucide} -> ${sap}`); continue; }
  if (viewBox && icon.vb !== viewBox) throw new Error(`${sap}: viewBox ${icon.vb} differs from ${viewBox}`);
  viewBox = icon.vb;
  out[lucide] = icon.d;
}
const names = [...new Set([...Object.values(MAP), ...EXTRA])];
for (const n of EXTRA) if (!read(n)) missing.push(`(extra) ${n}`);
if (missing.length) {
  console.error("Missing SAP icons:\n  " + missing.join("\n  "));
  process.exit(1);
}

fs.mkdirSync("src/sap", { recursive: true });
fs.writeFileSync(
  "src/sap/sapIconData.ts",
  `// GENERATED by scripts/gen-sap-icons.mjs — do not edit by hand.
// SAP Fiori "Horizon" icons (SAP-icons-v5, @ui5/webcomponents-icons), keyed by the Lucide icon they
// replace in the SAP theme. All share one viewBox and are drawn with fill="currentColor".
export const SAP_GLYPH_VIEWBOX = "${viewBox}";

export const SAP_GLYPHS: Record<string, string> = {
${Object.entries(out).map(([k, d]) => `  ${k}: ${JSON.stringify(d)},`).join("\n")}
};
`,
);
fs.writeFileSync(
  "src/sap/sapIcons.ts",
  `// GENERATED by scripts/gen-sap-icons.mjs — do not edit by hand.
// Registers the SAP icons used by <Icon name="…"/> in the SAP shell, launchpad and cards.
${names.sort().map((n) => `import "@ui5/webcomponents-icons/dist/${n}.js";`).join("\n")}
`,
);
console.log(`Wrote src/sap/sapIconData.ts (${Object.keys(out).length} glyphs, viewBox ${viewBox}) and src/sap/sapIcons.ts (${names.length} icons)`);
